"""Assembleur des prompts système avec prompt caching.

Stratégie d'injection MODULAIRE par stage :

- analyze : contexte produit minimal SEUL. L'IA observe le compte source de façon brute,
  sans biais avatars ni techniques copywriting déjà cadrées.
- persona : contexte + avatars (identification psychologique). Pas de techniques copywriting :
  la persona n'est pas du copywriting, c'est de l'incarnation.
- copy : contexte + avatars + techniques copywriting PURES (Master Copywriting Pure).
  L'IA fait les liens DYNAMIQUEMENT entre tweet source, persona, avatar cible, technique.
  Aucun lien pré-mâché : la diversité de production vient de la combinatoire qui émerge
  à chaque CSV, pas d'angles déjà tracés en amont.

Tous les gros blocs (>2k tokens) sont marqués cache_control=ephemeral pour bénéficier du
prompt caching Anthropic (90% d'économie après le 1er appel).
"""
from __future__ import annotations
from pathlib import Path
from typing import Any
from functools import lru_cache

from config import Config


@lru_cache(maxsize=8)
def _read_text(path_str: str) -> str:
    p = Path(path_str)
    if p.exists():
        return p.read_text(encoding="utf-8")
    return ""


def get_master_copywriting_pure() -> str:
    """Synthèse PURE des techniques copywriting, sans aucune mention de produit/avatar.

    Source : Knowledges/00-MASTER-COPYWRITING-PURE.md.
    L'ancien 00-MASTER-KNOWLEDGE-BASE.md (qui pré-mâchait les liens avec Compaatible/avatars)
    n'est plus injecté. Il reste comme document de référence humain.
    """
    return _read_text(str(Config.KNOWLEDGE_DIR / "00-MASTER-COPYWRITING-PURE.md"))


def get_avatars_full() -> str:
    """Fichier complet des avatars (1399 lignes, hook banks détaillés). Source unique."""
    return _read_text(str(Config.AVATARS_FILE))


