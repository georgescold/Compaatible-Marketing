                "un vrai diagnostic de growth marketer :\n\n"
                "1. **Mécanismes** (5 à 15) qui font marcher ce compte. Pour chacun : nom, "
                "description, exemples du source, pourquoi ça marche (psychologie / structure / "
                "promesse), compatibilité avec Compaatible (haute/moyenne/basse), et comment "
