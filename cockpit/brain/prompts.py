                "### Doctrine reply-trigger (≈ 1 tweet sur 4)\n\n"
                "X distingue, parmi les actions que déclenche un tweet, celles qui pèsent lourd "
                "et celles qui pèsent peu. Une **réponse** est nettement plus valorisée qu'un "
                "like : un like se fait en passant, une réponse engage. Un tweet qui se prend "
                "beaucoup de likes mais aucune réponse vaut moins, à signaux constants, qu'un "
                "tweet qui déclenche une vraie conversation.\n\n"
                "**Conséquence pratique** : environ **1 tweet sur 4** dans ton chunk doit être "
                "pensé pour faire répondre, pas seulement pour faire lire. Pas tous les tweets "
