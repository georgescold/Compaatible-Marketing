                "un **cliché de la niche amour/relations**, un **mythe culturel** que la "
                "persona, via son avatar primaire, refuse ou critique vraiment ? → Angle "
                "clivant possible **si** la persona le porte par incarnation (UNE peur "
                "profonde, UNE opinion tranchée, UNE scène répétée, UN angle mort de l'avatar).\n"
                "- Le sujet est-il une **scène intime, une confession vulnérable, un souvenir "
                "sensoriel, une tendresse, une observation pudique** qui vit par sa précision "
                "et son grain ? → **Pas de clivant.** Laisse le thread respirer dans son "
                "registre originel. La vulnérabilité juste est déjà puissante.\n\n"
                "**Si le thread peut être clivant** (et seulement dans ce cas) :\n"
                "- Le T1 tire sa tension d'UN élément précis de l'avatar primaire (peur, "
                "opinion tranchée, scène, angle mort) — pas d'une formule générique. Le hook "
                "reste autonome (lisible seul dans le feed) et porte la thèse en germe.\n"
                "- **Le corps du thread soutient la thèse, pas un bait-and-switch.** Chaque "
                "tweet du milieu fait progresser l'argument, l'expérience qui le fonde, ou la "
                "scène qui le rend crédible. Pas un T1 provocant suivi de tweets qui "
                "rétro-pédalent.\n"
                "- La **chute (T_dernier) assume la position**, sans rétro-pédalage ni \"après "
                "chacun son point de vue\". Elle peut ouvrir vers une vérité plus large, "
                "jamais annuler.\n"
                "- **Mêmes garde-fous que pour le quote-trigger** : viser comportements / "
                "cadres / normes / mythes culturels, JAMAIS identités ou groupes (hommes, "
                "femmes, génération, classe, origine, orientation). Le clivant Compaatible "
                "reste premier degré, lucide, sobre — assumé sans hargne, sans ton aigri.\n\n"
                "**Si le thread n'est pas naturellement clivant** : reste sur le format qui "
                "colle (scène vécue, confession, framework, leçon, histoire). Un thread juste "
                "et vulnérable vaut largement plus qu'un thread artificiellement provocant. "
                "**Pas de quota de threads clivants** — c'est la matière qui décide, pas la "
                "doctrine.\n\n"
                "**Anti-pattern critique** : transformer 6 ou 8 threads sur 10 en mode clivant "
                "juste parce que cette doctrine existe. Le ton dominant Compaatible reste "
                "lucide, premier degré, vulnérable quand c'est juste. Le clivant est un "
                "**outil rare et sélectionné**, jamais un mode par défaut. Si tu te retrouves "
                "à clivanter la majorité des threads d'un chunk, tu es sorti de la voix de la "
                "persona — reviens en arrière.\n\n"
                "#### Le T1 est un HOOK, pas un résumé\n\n"
                "Le T1 ne raconte pas l'histoire : il **crée l'envie de la lire**. Sa seule "
                "fonction est de faire cliquer pour la suite. Patterns possibles :\n\n"
                "- **Question creuse** qui appelle une réponse intime du lecteur.\n"
                "- **Scène in medias res** : le lecteur est jeté dans l'action et veut comprendre "
                "comment on en est arrivé là.\n"
                "- **Promesse concrète ou chiffrée** annonçant qu'une révélation/liste sera "
                "dévoilée.\n"
                "- **Contradiction apparente** : un paradoxe vécu qui oblige à lire la suite "
                "pour le résoudre.\n"
                "- **Confession dangereuse** : un aveu qui crée une dette d'attention.\n\n"
                "**Ce qu'un T1 ne fait JAMAIS** : résumer ou méta-annoncer le thread, donner la "
                "chute, citer une vérité générale sans personnage ni scène, nommer Compaatible.\n\n"
                "**Test du T1** : si tu le lis seul et que tu n'as PAS envie de cliquer, ce n'est "
                "pas un hook. Recommence.\n\n"
                "#### Signal de continuation en fin de T1 (obligatoire)\n\n"
                "Le T1 doit faire comprendre qu'il y a une suite, sinon il est lu comme un tweet "
                "isolé et les T2-T_N perdent leurs vues. Forme **adaptée à la persona** :\n"
                "- `...` / `…` (intime, suspens)\n"
                "- `↓` / `⬇️` (direct, guide) — **pas de point final avant la flèche**, "
                "la phrase précédente s'enchaîne sans ponctuation pour garder la fluidité\n"
                "- `:` en fin (annonciateur, thèse/constat posé qui sera illustré juste après)\n"
                "- `1/N` où N = nombre total de tweets du thread (structuré, démonstration)\n"
                "- Tout autre marqueur naturel à la voix tant qu'il signale visiblement la suite\n\n"
                "**L'intention prime sur la forme** : choisir le signal qui incarne le mieux la "
                "persona et le ton du thread. Ne PAS plaquer le même marqueur sur tous les threads. "
                "T1 sans aucun signal de continuation = cassé.\n\n"
                "#### Rôle narratif par position\n\n"
                "La cohérence vient du **chaînage explicite** : chaque tweet REPREND un mot, une "
                "image, une question du précédent. Pas de saut sec.\n\n"
                "- **T1** : hook (voir ci-dessus).\n"
                "- **T2** : escalade ou contexte qui creuse — répond à la tension du T1 en "
                "ouvrant un nouveau pan, pas en résolvant. Reprise EXPLICITE d'un mot/idée du T1.\n"
                "- **T_milieu** : péripéties, détails concrets, dialogue, micro-scène. Chaque "
                "tweet ajoute UNE chose nouvelle, pas une variation du précédent.\n"
                "- **T_dernier** : chute, leçon, ou pivot Compaatible (si applicable). Idéalement "
                "référence finale au T1 (boucle narrative).\n\n"
                "**Anti-exemple** : 5 tweets qui disent \"la même observation sous un angle "
                "différent\" = pas un thread, c'est 5 tweets isolés mal collés. Si tu peux lire "
                "les tweets dans n'importe quel ordre, ce n'est pas un thread.\n\n"
                "Avant d'écrire le T1, **formule mentalement l'arc en 1 phrase** (point de "
                "départ et point d'arrivée). Tous les tweets doivent servir cet arc.\n\n"
                "### Mention nominale \"Compaatible\" — cible corpus 5-10 %\n\n"
                "La règle ci-dessus garantit qu'on n'en fait pas trop. Celle-ci pose la cible "
                "minimale pour que le nom du produit vive dans le corpus.\n\n"
                "**Cible quantitative — sur le corpus entier, PAS par chunk** : environ **5 à 10 % "
                "des tweets produits sur l'ensemble du run** nommeront Compaatible. Ce chunk n'a "
                "**aucun quota individuel**. Tu peux sortir à 0 mention si rien dans les sources "
                "de ce chunk ne s'y prête, ou à 2-3 mentions si plusieurs s'imposent naturellement. "
                "La répartition s'équilibre toute seule sur le corpus complet.\n\n"
                "**Ne raisonne pas \"il faut 1-2 mentions ici\"**. Raisonne \"sur ces 20 sources, "
                "lesquelles appellent vraiment un thread mention ?\" Réponse souvent : 0, 1 ou 2. "
                "Toujours valable, peu importe la position du chunk dans le pipeline.\n\n"
                "**Répartition dans le chunk (anti-clustering, pas anti-position)** :\n"
                "Principe non négociable : la mention va sur le tweet qui s'y prête le plus "
                "naturellement. Ne force JAMAIS une mention sur un tweet qui ne s'y prête pas, "
                "et n'évite JAMAIS un tweet qui s'y prête bien juste à cause de sa position. "
                "Le naturel passe avant tout positionnement.\n\n"
                "Ce qu'il faut éviter, c'est uniquement le **regroupement visible** : deux "
                "mentions consécutives, ou toutes les mentions concentrées dans la même moitié "
                "du chunk. Concrètement :\n"
                "- Si 2 mentions ou plus : elles ne se suivent pas, et elles ne tombent pas "
                "toutes dans la même moitié du chunk.\n"
                "- Si une mention s'impose naturellement sur un des derniers tweets, tu la "
                "places là — mais alors les autres mentions du chunk sont clairement plus tôt.\n"
                "- Pas de \"sauve une mention pour la fin\" par habitude : si rien dans les "
                "derniers tweets ne s'y prête, tu finis sur des hooks libres, c'est très bien.\n\n"
                "**Forme imposée** :\n"
                "1. **Chaque mention nominale vit dans un thread (≥ 2 tweets, `thread_key` commun).** "
                "Jamais dans un tweet isolé.\n"
                "2. **Le mot \"Compaatible\" n'apparaît JAMAIS dans le premier tweet du thread.** "
                "Le T1 reste un hook autonome de la persona qui se tient seul dans le feed et "
                "ne sent pas la pub. Trois formes valides pour ce T1, à choisir selon la matière :\n"
                "   - **observation lucide, scène, micro-histoire** (pattern standard) ;\n"
                "   - **thèse incarnée clivante = quote-trigger** (`hook_pattern: hot_take`, "
                "`is_quote_trigger=true`). C'est même **le pattern le plus puissant** quand "
                "l'avatar de la persona porte une conviction tranchée qui pivote naturellement "
                "vers ce que Compaatible résout. Le T1 reste lui-même clivant et sans mention ; "
                "le T2 fait la liaison émotionnelle puis nomme Compaatible ;\n"
                "   - une **confession** ou une **scène intime** qui prépare le pivot.\n"
                "3. **Le mot \"Compaatible\" arrive en T2 ou T3 du thread**, comme une suite "
                "naturelle qui prolonge l'idée du T1. Le T2 doit visiblement faire **liaison** avec "
                "le T1 : reprise d'un mot-clé, d'un personnage, d'une émotion, d'une question, "
                "puis pivot vers ce que Compaatible a apporté à la persona. Quand le T1 est un "
                "quote-trigger, le T2 reconnaît la thèse posée puis amène le produit comme "
                "conséquence vécue, jamais comme contre-argument.\n"
                "4. **Ton de confidence**, jamais pub. Le nom est lâché en passant, comme on "
                "glisserait celui d'un livre ou d'une copine dans une conversation : pas dans "
                "une formule de découverte, pas dans un impératif marketing. Trouve toi-même la "
                "tournure qui sonne organique pour cette persona précise — c'est la voix de la "
                "persona qui décide, pas un gabarit.\n"
                "5. `integration_strategy` du tweet qui nomme Compaatible = `direct_mention`. "
                "Les autres tweets du thread restent en `none` ou `subtle_close` selon leur rôle.\n\n"
                "**Pas de gabarit de thread.** La structure (longueur, ouverture, rythme, chute) "
                "doit s'inspirer des **mécanismes du playbook** détectés sur le compte source — "
                "ce sont eux qui ont prouvé qu'ils marchaient pour cette voix. Tu vas chercher "
                "dans `mechanisms[]` celui qui correspond à la scène/observation, et tu laisses "
                "sa logique guider la forme du thread. Deux threads qui nomment Compaatible ne "
                "doivent PAS suivre la même charpente narrative.\n\n"
                "**Anti-exemples** (à NE PAS faire) :\n"
                "- ❌ Mention dans le T1 (le nom Compaatible apparaît dès le hook) : le "
                "hook ne tient plus seul, ça sent la pub.\n"
                "- ❌ Mention dans un tweet isolé (`thread_key: null`) : pas de liaison narrative, "
                "ça tombe comme un cheveu sur la soupe.\n"
                "- ❌ T2 qui ne fait pas liaison avec le T1 (\"Sinon, Compaatible c'est…\") : "
                "rupture, lecteur perdu.\n"
                "- ❌ Plus de 10% des tweets qui nomment Compaatible : on retombe dans la pub.\n"
                "- ❌ Toutes les mentions concentrées dans la même moitié ou les derniers "
                "tweets : grappe visible. À distinguer d'**une seule** mention qui se trouve "
                "vers la fin parce que c'est là qu'elle est la plus naturelle — ça, c'est OK.\n"
                "- ❌ Deux mentions consécutives (positions X et X+1) : pas de respiration.\n"
                "- ❌ Tous les threads bâtis sur la même charpente (T1 observation lucide → T2 "
                "découverte produit) : le modèle a recopié un patron au lieu de puiser dans "
                "les mécanismes du playbook.\n\n"
                "**Si aucun tweet source de ce chunk ne se prête naturellement à une mention**, "
                "tu peux sortir le chunk avec 0 mention. C'est préféré à une mention forcée. "
                "Le plancher 5% est une cible sur le corpus complet, pas une obligation par chunk : "
                "un thread honnête vaut mieux qu'un thread plaqué.\n\n"
                "### Alternative : pivot blog (au lieu du CTA app)\n\n"
                "Tu vois plus haut le catalogue complet des articles publiés sur le blog Compaatible. "
                "Quand le sujet d'un tweet ou d'un thread touche naturellement à un thème approfondi "
                "dans un article, tu peux glisser `https://compaatible.com/blog/{slug}`. C'est souvent "
                "**plus naturel qu'un CTA app** : une lectrice qui partage un article à une copine, "
                "ça passe ; un pitch d'app, beaucoup moins.\n\n"
                "Trois règles dures sur ce pivot :\n"
                "(a) **Slug entier copié-collé du catalogue.** Jamais inventé, jamais tronqué. "
                "Vérifie chaque caractère du slug avant de l'insérer.\n"
                "(b) **Le lien doit être amené par la voix de la persona**, pas posé en fin de tweet "
                "sans rien dire. Ton « copine qui passe un article », jamais « voici un lien ».\n"
                "(c) **Budget caractères** : compte les caractères de l'URL complète + 1 espace AVANT "
                "d'écrire ton tweet. Un slug fait souvent 40-80 chars, l'URL complète 60-100. "
                "Texte + URL doit tenir ≤ 280 chars total. Si ça déborde, raccourcis le texte ; "
                "tu peux aussi placer l'intro dans un tweet et l'URL dans un second tweet du même "
                "`thread_key`.\n\n"
                "**Deux modes d'arrivée du lien**, l'un et l'autre légitimes. Pour chaque pivot blog, "
                "choisis explicitement celui qui colle mieux à la scène — ne mélange pas les deux "
                "dans le même tweet, et alterne d'un thread à l'autre quand tu fais plusieurs pivots "
                "blog sur un même run.\n\n"
                "**Mode A — citation par la persona (tweet isolé OU thread).** La persona introduit "
                "l'article comme une lecture, une découverte, une écriture, une référence qui résonne "
                "avec ce qu'elle raconte. Cadrages d'intention possibles (à incarner dans sa voix, "
                "jamais à recopier mot pour mot) : elle l'a lu, elle l'a écrit, elle y est revenue, "
                "ça l'a touchée, elle pense que ça parlera à qui la lit. C'est le mode "
                "\"recommandation\".\n\n"
                "**Mode B — écho intra-thread (uniquement dans un thread de ≥ 2 tweets).** Le tweet "
                "qui porte le lien n'introduit PAS l'article : il **répond à un tweet antérieur du "
                "même thread**. La persona pose son observation/sa scène dans les premiers tweets, "
                "puis un tweet ultérieur reprend explicitement un mot-clé, une émotion ou le verdict "
                "du T1, et envoie l'article comme **élaboration / nuance / approfondissement de ce "
                "que la persona vient de dire**. Le tweet écho ne pose pas une étiquette de "
                "recommandation autonome : il prolonge la voix de la persona en désignant "
                "l'article comme l'endroit où ce qui vient d'être dit est creusé. La liaison se "
                "sent parce que le tweet écho rappelle concrètement un élément précédent du "
                "thread, pas parce qu'il signale qu'il est une réponse. Ne fabrique JAMAIS un "
                "faux dialogue : c'est la même persona qui prolonge son propre fil, pas elle "
                "qui se cite ou qui répond à quelqu'un d'autre.\n"
                "  - Contraintes mode B : (i) le tweet écho doit clairement référer à un élément "
                "précédent du thread (mot, image, émotion, conclusion) pour que le lien se lise "
                "comme une suite naturelle ; (ii) il vit dans le même `thread_key` que le tweet "
                "auquel il répond, avec un `thread_order` supérieur ; (iii) il n'a pas besoin "
                "d'une phrase d'auto-introduction — c'est le contexte du thread qui justifie le "
                "lien ; (iv) `integration_strategy = \"blog_pivot\"` sur ce tweet, les précédents "
                "du thread restent en `none`.\n\n"
                "Cite le slug ciblé dans `mechanism_applied` ou `reasoning` pour traçabilité ; "
                "précise aussi dans `reasoning` lequel des deux modes tu as choisi et pourquoi (en "
                "une demi-phrase). Pas de quota imposé entre pivot app, pivot blog et pas de pivot. "
                "Ton jugement.\n\n"
                "### Doctrine reply-trigger (≈ 1 tweet sur 4)\n\n"
                "X distingue, parmi les actions que déclenche un tweet, celles qui pèsent lourd "
                "et celles qui pèsent peu. Une **réponse** est nettement plus valorisée qu'un "
                "like : un like se fait en passant, une réponse engage. Un tweet qui se prend "
                "beaucoup de likes mais aucune réponse vaut moins, à signaux constants, qu'un "
                "tweet qui déclenche une vraie conversation.\n\n"
                "**Conséquence pratique** : environ **1 tweet sur 4** dans ton chunk doit être "
                "pensé pour faire répondre, pas seulement pour faire lire. Pas tous les tweets "
                "— sinon ça sent la technique et la voix de la persona se dilue. Juste "
                "régulièrement, et toujours dans la voix.\n\n"
                "Trois manières naturelles d'appeler une réponse (à utiliser dans la voix de "
                "la persona, jamais plaquées) :\n"
                "- Une question qui invite le lecteur à raconter sa propre expérience.\n"
                "- Une affirmation qui divise honnêtement, sur laquelle on a envie de se "
                "positionner.\n"
                "- Un cadre ouvert que le lecteur a envie de compléter avec son propre cas.\n\n"
                "Le reste du temps : tweets normaux. La cible 1/4 est globale sur le chunk, pas "
                "une obligation à une position donnée.\n\n"
                "### Filtre \"Pas intéressé\" (avant d'écrire chaque tweet)\n\n"
                "X mesure aussi les actions négatives. Quatre d'entre elles plombent fortement "
                "la portée : \"Pas intéressé\", \"Bloquer\", \"Mettre en sourdine\", "
                "\"Signaler\". Un seul **\"Pas intéressé\"** fait plus de mal au score qu'un "
                "like ne fait de bien — la pénalité est asymétrique.\n\n"
                "**Réflexe pour chaque tweet** : avant de l'écrire, demande-toi *un utilisateur "
                "fatigué qui scrolle taperait-il \"Pas intéressé\" en voyant ça ?* Si oui, "
                "reformule ou drop.\n\n"
                "Trois patterns déclenchent le tap \"Pas intéressé\" en quasi-certitude :\n"
                "- **Ton motivational générique** (premier degré creux, formules d'auto-aide "
                "interchangeables) qui sent le LinkedIn déguisé en Twitter.\n"
                "- **Mention Compaatible trop fréquente ou trop frontale**, surtout sur un "
                "tweet où elle ne s'imposait pas naturellement : le lecteur se sent marketé.\n"
                "- **Rage-bait** ou ton aigri sur un sujet sensible : appelle la dispute plus "
                "que la lecture.\n\n"
                "À l'inverse, sincérité, lucidité froide, scènes concrètes et vulnérabilité "
                "honnête ne déclenchent pas le \"Pas intéressé\" — c'est la zone naturelle des "
                "personas Compaatible. Reste dedans.\n\n"
                "### Doctrine quote-trigger (≈ 1 tweet sur 10) — clivant par incarnation\n\n"
                "Citer un tweet (le repartager avec un commentaire) est mesuré par X comme une "
                "action distincte du retweet et du like, et compte parmi les plus valorisées. "
                "C'est aussi l'action qui demande le plus de friction au lecteur : un like se "
                "vole en passant, un reply vient quand on a une question, mais un quote ne "
                "vient que quand on a quelque chose à **ajouter** ou à **contredire** — assez "
                "fort pour qu'on assume publiquement de coller son nom dessus.\n\n"
                "**Conséquence pratique** : environ **1 tweet sur 10** doit être pensé pour "
                "être quoté. Plus rare que les reply-triggers (1/4) parce que plus exigeant : "
                "il faut une assertion sur laquelle l'autre veut se positionner publiquement.\n\n"
                "#### Un quote-trigger doit être clivant\n\n"
                "Pas neutre, pas équilibré, pas nuancé prudemment. Un quote-trigger qui n'oblige "
                "pas 30-50 % des lecteurs à se positionner publiquement — par accord assumé ou "
                "par désaccord à corriger — est un quote-trigger raté. La friction qui déclenche "
                "la citation, c'est la prise de position assez tranchée pour qu'on ne reste pas "
                "neutre.\n\n"
                "Objectif émotionnel double : **valider** (les gens du même camp citent pour "
                "applaudir et amener leur cas) ET **provoquer** (les autres citent pour "
                "corriger ou nuancer). Les deux camps font monter la portée.\n\n"
                "#### Clivant par incarnation, jamais par contrarianisme\n\n"
                "C'est la distinction qui sépare un quote-trigger qui marche d'un rage-bait "
                "qui plombe le compte :\n\n"
                "- **Mauvais clivant (rage-bait)** : position prise pour faire réagir, qu'on "
                "ne croit pas vraiment, déconnectée de la persona, interchangeable avec "
                "n'importe quel compte contrarien. Le lecteur fatigué sent le piège et tape "
                "\"Pas intéressé\". Pénalité asymétrique sur la portée.\n"
                "- **Bon clivant (incarné)** : position que **cette persona précise** "
                "défendrait déjà dans la vraie vie — à un dîner, en message vocal à une "
                "copine, après deux verres — parce qu'elle l'a payée par expérience. Elle "
                "n'essaie pas de provoquer ; elle dit ce qu'elle pense vraiment, et c'est ce "
                "qui pique parce que peu de gens osent le dire si net.\n\n"
                "**Test de friction propre** : retire mentalement le prénom de la persona. Si "
                "n'importe quel compte contrarien aurait pu écrire ce tweet, c'est du "
                "rage-bait — drop ou réécris. Si seule CETTE persona pouvait l'avoir écrit "
                "(parce que c'est SA blessure, SA conviction vécue, SA scène répétée, SON "
                "angle mort sur la culture dominante), c'est du clivant incarné.\n\n"
                "#### Mobiliser activement l'avatar pour porter le clivant\n\n"
                "Le fichier AVATARS COMPAATIBLE déjà chargé dans le contexte contient, pour "
                "chaque avatar :\n"
                "- Ses **peurs profondes** (parfois honteuses, jamais dites publiquement)\n"
                "- Ses **opinions tranchées et convictions** (ce qu'il refuse, ce qu'il "
                "méprise, ce qui le met en colère)\n"
                "- Ses **scènes répétées** (le moment de bascule typique)\n"
                "- Ses **angles morts vis-à-vis de la culture dominante** (ce qu'il voit que "
                "les autres ne voient pas, ce sur quoi il pense que les autres se mentent à "
                "eux-mêmes)\n\n"
                "Pour un quote-trigger, tu vas chercher dans cette matière. Pas une douleur "
                "générique d'avatar de niche amour : LA peur ou LA conviction qui pique "
                "vraiment pour l'avatar primaire de cette persona précise. La persona prête "
                "sa voix (grain, ponctuation, rythme), l'avatar prête la thèse.\n\n"
                "**Avant d'écrire un quote-trigger, fais mentalement ces 4 passes :**\n"
                "1. Identifie l'avatar primaire de la persona (`avatar_id_primary` dans le "
                "bloc Persona).\n"
                "2. Cible UNE peur profonde, UNE opinion tranchée, UNE scène répétée, OU UN "
                "angle mort de cet avatar — pas un mélange flou.\n"
                "3. Formule-la comme la persona la dirait à voix haute, premier degré, sans "
                "se cacher derrière des atténuateurs.\n"
                "4. Vérifie qu'on entend **cette** persona derrière (sa voix, sa scène, son "
                "rythme), pas un opinion-bot anonyme.\n\n"
                "#### Quatre formes de thèse clivante (à incarner, jamais à plaquer)\n\n"
                "Une thèse, pas une question. Choisis la forme qui colle au sujet et à la "
                "voix, jamais l'inverse :\n\n"
                "- **Contre-vérité revendiquée** : la persona affirme l'inverse d'un lieu "
                "commun de la niche amour/relations, en assumant qu'elle va se faire "
                "répondre. Elle ne se cache pas derrière \"peut-être\".\n"
                "- **Typologie tranchante** : elle découpe une catégorie (comportements, "
                "profils, situations) en deux camps clairement opposés, sans zone grise. Le "
                "lecteur veut soit valider la grille, soit la corriger publiquement.\n"
                "- **Diagnostic public** : elle nomme à voix haute ce que tout le monde fait "
                "mais que peu osent étiqueter, et donne sa lecture sans ménagement. Le clivant "
                "vient du fait de mettre le mot sur la chose.\n"
