        "- Imperfections : zones surexposées (fenêtre cramée), zones d'ombre profondes, "
        "lumière inégale — c'est ce qui rend la photo vraie.\n\n"
        "### 7. DÉCOR ET DÉTAILS ANCRANTS — l'environnement raconte sa vie\n"
        "Le décor doit raconter SA vie quotidienne précise. Choisis 2 à 4 éléments "
        "visibles (jamais 7+) qui appartiennent vraiment à elle. Quelques registres :\n"
