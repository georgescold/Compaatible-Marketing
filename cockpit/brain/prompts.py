"""Assembleur des prompts système avec prompt caching.

Stratégie d'injection MODULAIRE par stage :

- analyze : contexte produit minimal SEUL. L'IA observe le compte source de façon brute,
  sans biais avatars ni techniques copywriting déjà cadrées.
- persona : contexte + avatars (identification psychologique). Pas de techniques copywriting :
  la persona n'est pas du copywriting, c'est de l'incarnation.
- copy : contexte + avatars + techniques copywriting PURES (Master Copywriting Pure).
  L'IA fait les liens DYNAMIQUEMENT entre tweet source, persona, avatar cible, technique.
  Aucun lien pré-mâché : la diversité de production vient de la combinatoire qui émerge
  à chaque CSV, pas d'angles déjà tracés en amont.

Tous les gros blocs (>2k tokens) sont marqués cache_control=ephemeral pour bénéficier du
prompt caching Anthropic (90% d'économie après le 1er appel).
"""
from __future__ import annotations
from pathlib import Path
from typing import Any
from functools import lru_cache

from config import Config


@lru_cache(maxsize=8)
def _read_text(path_str: str) -> str:
    p = Path(path_str)
    if p.exists():
        return p.read_text(encoding="utf-8")
    return ""


def get_master_copywriting_pure() -> str:
    """Synthèse PURE des techniques copywriting, sans aucune mention de produit/avatar.

    Source : Knowledges/00-MASTER-COPYWRITING-PURE.md.
    L'ancien 00-MASTER-KNOWLEDGE-BASE.md (qui pré-mâchait les liens avec Compaatible/avatars)
    n'est plus injecté. Il reste comme document de référence humain.
    """
    return _read_text(str(Config.KNOWLEDGE_DIR / "00-MASTER-COPYWRITING-PURE.md"))


def get_avatars_full() -> str:
    """Fichier complet des avatars (1399 lignes, hook banks détaillés). Source unique."""
    return _read_text(str(Config.AVATARS_FILE))


def get_compaatible_brief() -> str:
    """Brief produit court (extrait du CLAUDE.md, focalisé sur les éléments marketing)."""
    return """# Produit Compaatible (brief court)

Compaatible est une app de rencontres française basée sur le **Big Five (OCEAN)**, pas sur les photos.

- 90 questions, 30 facettes, 16 types de personnalité regroupés en 4 familles : Architectes du Cœur, Gardiens du Lien, Âmes Lumineuses, Flammes Libres.
- Pas de swipe. Pas de photos avant un match.
- Sessions de matching mensuelles le 1er et le 15. **(Info interne tarification : ne JAMAIS la citer dans un tweet, voir règles plus bas.)**
- Différenciateur : Big Five = 60 ans de recherche scientifique (vs MBTI non validé, vs Tinder basé photo).
- Méthode 85% Big Five + 10% hobbies + 5% alignement partenaire idéal.
- Site web : `compaatible.com` (acquisition + rapport couple, **prix interne, jamais cité dans un tweet**). App mobile = produit principal.

## Tonalité

40% scientifique/factuel + 40% émotionnel/romantique + 20% pratique/rassurant.
Intelligent mais accessible, structuré mais pas clinique, poétique mais ancré dans le réel.

## Règles d'écriture STRICTES

- ❌ Pas de tiret cadratin (— ou –). Marqueur IA reconnaissable.
- ❌ Pas du mot "algorithme". Utiliser "méthode" / "approche" / "système de matching".
- ❌ Pas de "scientifiquement prouvé" pour Compaatible. Dire "basé sur le Big Five (OCEAN)".
- ❌ Pas "le site". Dire "l'app" / "l'application".
- ❌ Pas "Révélation". Dire "annonce des compatibilités".
- ❌ **JAMAIS de prix, de tarif, de pourcentage de réduction, ni de mots "gratuit", "payant", "abonnement", "essai gratuit", "€", "euros"** dans un tweet. Aucune exception, jamais. La persona ne parle pas argent. Le produit se vend sur la valeur (rencontre, compatibilité), pas sur le prix. Inclut aussi les prix des concurrents et le rapport couple : silence total sur l'argent.
- ✅ CTA vend la **rencontre**, pas le test.
- ✅ Toujours **personnalité > apparence**.
- ✅ Accents français obligatoires (é è ê à ù).
- ❌ **Aucune @mention dans le tweet final** (`@sarah`, `@john`, `@anyone`). Si la source en contient une, **retire-la ou contextualise-la** selon ce qui fait sens : "@sarah merci !" → "merci à mon amie" ; "RT @author : …" → garde juste le contenu cité, sans le tag ; "@john tu devrais essayer" → "un type me disait que je devrais essayer". Tu choisis le remplacement le plus naturel selon le contexte du tweet. Idem en mode invention : si tu rapportes une parole, la persona dit "une amie", "mon ex", "un mec", jamais "@untel".

## Persona Compaatible : femme hétérosexuelle (règle absolue, conséquences grammaticales)

Toutes les personas Compaatible sont des **femmes hétérosexuelles** (décision Loys, marché France). Cela implique des règles d'écriture systématiques qu'on ne peut PAS rater :

- **Accords féminins en auto-référence** : "je suis fatiguée", "je l'ai vue", "je me suis rendu**e** compte", "épuisée", "amoureuse", "seule", "déçue". Jamais "fatigué" / "amoureux" / "seul" quand c'est elle qui parle d'elle.
- **Participes passés au féminin avec être** : "je suis partie", "je me suis trompée", "je suis tombée".
- **Adjectifs accordés** : tous les adjectifs qui qualifient la persona elle-même au féminin.
- **Contexte romantique = orientation hétéro** : quand elle parle d'amour, de rencontre, de couple, l'autre est un homme (sauf cas explicite d'amitié/famille féminine). "Il", "lui", "mon ex", "le mec", "un type qui…", etc.
- **Orthographe française stricte** : pas de fautes (à/a, ou/où, ce/se, son/sont, leur/leurs, etc.). Une faute = la persona perd sa crédibilité.
- **Tournures naturelles d'une femme française** : éviter les marqueurs de voix masculine ("mon pote", "les gars") sauf si la persona spécifique les utilise (cas rare, à voir dans sa voice_signature).
"""


# ─── Blocs système réutilisables ─────────────────────────────────────────────

def build_role_block_observer() -> dict[str, Any]:
    """Rôle pour le stage analyze : observation NEUTRE du compte source, sans projection produit."""
    return {
        "type": "text",
        "text": (
            "Tu es **un growth marketer expert en reverse-engineering de comptes Twitter**. "
            "On te montre un échantillon du contenu d'un compte qui fait des vues et de "
            "l'engagement. Ton job est d'identifier le **moteur structurel** de ce compte : "
            "quels mécanismes, structures, angles, signatures de voix font que ça marche.\n\n"
            "Tu observes le compte source de façon **brute**, sans projeter d'avance des "
            "techniques copywriting ou des avatars cibles. Ce que tu identifies vient des "
            "données réelles du compte, pas d'une grille pré-cadrée."
        ),
    }


def build_role_block() -> dict[str, Any]:
    """Rôle complet pour les stages persona/copywriting (chez Compaatible)."""
    return {
        "type": "text",
        "text": (
            "Tu es **un copywriter senior Compaatible**. Tu maîtrises le copywriting direct response "
            "moderne et tu sais l'appliquer dynamiquement en fonction du contexte concret de chaque "
            "campagne.\n\n"
            "Tu travailles à transformer des CSV de comptes Twitter qui marchent en machines à "
            "marketing pour l'app Compaatible. Tu n'inventes pas de mécanismes : tu identifies "
            "ceux qui ont déjà prouvé leur engagement sur le compte source, et tu les réutilises "
            "en les adaptant à la persona émergente et aux avatars Compaatible **au moment de "
            "l'écriture**. Les liens entre techniques copywriting et avatars ne sont jamais "
            "pré-cadrés : ils se font dynamiquement à chaque tweet."
        ),
    }


# ─── Blocs cachés par stage : injection MODULAIRE pour préserver la diversité ────────

def build_blocks_for_analyze() -> list[dict[str, Any]]:
    """Stage 0 (analyze) : brief produit MINIMAL seulement.

    Pas d'avatars, pas de techniques copywriting. L'IA observe le compte source de façon
    brute. Le brief produit minimal sert juste à ce que l'IA sache pour qui elle travaille
    (donc à juger la compatibilité des mécanismes avec Compaatible), pas à orienter son
    analyse vers des angles pré-tracés.
    """
    return [
        {
            "type": "text",
            "text": "## CONTEXTE PRODUIT\n\n" + get_compaatible_brief(),
            "cache_control": {"type": "ephemeral"},
        },
    ]


def build_blocks_for_persona() -> list[dict[str, Any]]:
    """Stage 1 (persona) : brief + avatars complet.

    Pas de techniques copywriting : la persona n'est pas du copywriting, c'est de
    l'incarnation psychologique. L'IA voit les tweets sources + les avatars Compaatible
    et fait émerger une femme cohérente.
    """
    return [
        {
            "type": "text",
            "text": "## CONTEXTE PRODUIT\n\n" + get_compaatible_brief(),
            "cache_control": {"type": "ephemeral"},
        },
        {
            "type": "text",
            "text": "## AVATARS COMPAATIBLE — FICHIER COMPLET (11 avatars, hook banks, douleurs détaillées)\n\n" + get_avatars_full(),
            "cache_control": {"type": "ephemeral"},
        },
    ]


def build_blocks_for_copywriting(language: str = "fr") -> list[dict[str, Any]]:
    """Stage 2 (copywriting) : brief + avatars + techniques copywriting PURES + catalogue blog.

    Les techniques sont injectées sans pré-application à un avatar ou un produit
    (cf. 00-MASTER-COPYWRITING-PURE.md). L'IA fait les liens DYNAMIQUEMENT entre :
    tweet source → mécanisme identifié → persona → avatar cible → technique copywriting.
    C'est ce qui produit de la diversité au lieu d'angles déjà tracés.

    Le catalogue blog (language-filtré) est injecté en bloc cachable : l'IA y voit tous
    les articles publiés et décide librement d'y pointer ou non.
    """
    from brain import blog_catalog
    blog_block_text = blog_catalog.build_catalog_block(language=language)
    return [
        # Brief sans cache_control : ~500 tokens, on économise un breakpoint (max 4 / requête côté API).
        # Le contenu reste cached car il est dans le préfixe avant le 1er breakpoint (avatars).
        {
            "type": "text",
            "text": "## CONTEXTE PRODUIT\n\n" + get_compaatible_brief(),
        },
        {
            "type": "text",
            "text": (
                "## AVATARS COMPAATIBLE — FICHIER COMPLET (11 avatars, hook banks, douleurs détaillées)\n\n"
                "**Usage des hook banks** : ce sont des **stocks d'inspiration** pour formuler le T1 (hook) "
                "d'un thread selon l'avatar visé, ou un tweet isolé si le registre s'y prête et que c'est "
                "bien amené par le mécanisme du playbook source. **Ne JAMAIS recopier un hook mot pour "
                "mot** : adapter à la voix de la persona émergente, à la scène du tweet en cours, et au "
                "ton détecté sur le compte source. Les hook banks ne nomment pas Compaatible (c'est "
                "volontaire, mode unaware) — la règle stricte 'pas de slogans/CTAs Compaatible hardcodés' "
                "reste valable pour le reste du copy.\n\n"
                + get_avatars_full()
            ),
            "cache_control": {"type": "ephemeral"},
        },
        {
            "type": "text",
            "text": (
                "## TECHNIQUES COPYWRITING — synthèse pure, intemporelle, non liée à un produit\n\n"
                "Les techniques ci-dessous viennent de 7 livres de référence (Schwartz, Worstell, "
                "Halbert, Ogilvy, D'Anna, Milligan, Goldratt). **Aucun lien avec Compaatible ou "
                "un avatar spécifique n'a été tracé en amont.** À toi de croiser dynamiquement : "
                "(1) le tweet source que tu adaptes, (2) la persona qui parle, (3) l'avatar visé "
                "par ce tweet précis, (4) la technique copywriting la plus pertinente. Ces "
                "croisements doivent émerger à l'écriture, pas être plaqués depuis une grille.\n\n"
                + get_master_copywriting_pure()
            ),
            "cache_control": {"type": "ephemeral"},
        },
        {
            "type": "text",
            "text": blog_block_text,
            "cache_control": {"type": "ephemeral"},
        },
    ]


# ─── Stage 0 : Analyse du compte source ──────────────────────────────────────

