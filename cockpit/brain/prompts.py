                "3. Formule-la comme la persona la dirait à voix haute, premier degré, sans "
                "se cacher derrière des atténuateurs.\n"
                "4. Vérifie qu'on entend **cette** persona derrière (sa voix, sa scène, son "
                "rythme), pas un opinion-bot anonyme.\n\n"
                "#### Quatre formes de thèse clivante (à incarner, jamais à plaquer)\n\n"
                "Une thèse, pas une question. Choisis la forme qui colle au sujet et à la "
                "voix, jamais l'inverse :\n\n"
                "- **Contre-vérité revendiquée** : la persona affirme l'inverse d'un lieu "
                "commun de la niche amour/relations, en assumant qu'elle va se faire "
                "répondre. Elle ne se cache pas derrière \"peut-être\".\n"
                "- **Typologie tranchante** : elle découpe une catégorie (comportements, "
                "profils, situations) en deux camps clairement opposés, sans zone grise. Le "
                "lecteur veut soit valider la grille, soit la corriger publiquement.\n"
                "- **Diagnostic public** : elle nomme à voix haute ce que tout le monde fait "
                "mais que peu osent étiqueter, et donne sa lecture sans ménagement. Le clivant "
                "vient du fait de mettre le mot sur la chose.\n"
                "- **Refus assumé** : elle déclare un truc qu'elle ne fera plus jamais ou "
                "qu'elle n'a jamais voulu accepter, à contre-courant de la pression sociale "
                "dominante de son avatar. Le clivant vient du non.\n\n"
                "Ces formes sont des **architectures**, pas des gabarits de phrase. Aucune "
                "formulation type n'est donnée ici, volontairement : l'écriture émerge de la "
                "voice_signature de la persona × de la matière de l'avatar, jamais d'un "
                "patron recopié.\n\n"
