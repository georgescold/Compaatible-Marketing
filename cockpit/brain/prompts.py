                "registre originel. La vulnérabilité juste est déjà puissante.\n\n"
                "**Si le thread peut être clivant** (et seulement dans ce cas) :\n"
                "- Le T1 tire sa tension d'UN élément précis de l'avatar primaire (peur, "
                "opinion tranchée, scène, angle mort) — pas d'une formule générique. Le hook "
                "reste autonome (lisible seul dans le feed) et porte la thèse en germe.\n"
                "- **Le corps du thread soutient la thèse, pas un bait-and-switch.** Chaque "
                "tweet du milieu fait progresser l'argument, l'expérience qui le fonde, ou la "
                "scène qui le rend crédible. Pas un T1 provocant suivi de tweets qui "
                "rétro-pédalent.\n"
                "- La **chute (T_dernier) assume la position**, sans rétro-pédalage ni \"après "
                "chacun son point de vue\". Elle peut ouvrir vers une vérité plus large, "
                "jamais annuler.\n"
                "- **Mêmes garde-fous que pour le quote-trigger** : viser comportements / "
                "cadres / normes / mythes culturels, JAMAIS identités ou groupes (hommes, "
                "femmes, génération, classe, origine, orientation). Le clivant Compaatible "
                "reste premier degré, lucide, sobre — assumé sans hargne, sans ton aigri.\n\n"
                "**Si le thread n'est pas naturellement clivant** : reste sur le format qui "
                "colle (scène vécue, confession, framework, leçon, histoire). Un thread juste "
                "et vulnérable vaut largement plus qu'un thread artificiellement provocant. "
                "**Pas de quota de threads clivants** — c'est la matière qui décide, pas la "
                "doctrine.\n\n"
                "**Anti-pattern critique** : transformer 6 ou 8 threads sur 10 en mode clivant "
                "juste parce que cette doctrine existe. Le ton dominant Compaatible reste "
                "lucide, premier degré, vulnérable quand c'est juste. Le clivant est un "
                "**outil rare et sélectionné**, jamais un mode par défaut. Si tu te retrouves "
                "à clivanter la majorité des threads d'un chunk, tu es sorti de la voix de la "
                "persona — reviens en arrière.\n\n"
                "#### Le T1 est un HOOK, pas un résumé\n\n"
                "Le T1 ne raconte pas l'histoire : il **crée l'envie de la lire**. Sa fonction "
                "unique est de faire cliquer sur le thread pour voir la suite. Il doit produire "
                "une de ces tensions :\n\n"
                "- **Question creuse** qui appelle une réponse intime du lecteur.\n"
                "- **Scène in medias res** : le lecteur est jeté dans l'action et veut comprendre "
                "comment on en est arrivé là.\n"
                "- **Promesse concrète ou chiffrée** : le T1 annonce qu'une révélation/liste sera "
                "dévoilée, le lecteur reste pour l'avoir.\n"
                "- **Contradiction apparente** : un paradoxe vécu qui oblige à lire la suite pour "
                "le résoudre.\n"
                "- **Confession dangereuse** : un aveu qui crée une dette d'attention.\n\n"
                "**Ce qu'un T1 ne fait JAMAIS** :\n"
                "- ❌ Résumer ou méta-annoncer le thread (\"je vais te raconter…\", \"en 5 tweets…\")\n"
                "- ❌ Donner la chute (le punch arrive en T_last, pas en T1)\n"
                "- ❌ Citer une vérité générale sans personnage ni scène\n"
                "- ❌ Nommer Compaatible (règle déjà posée plus bas)\n\n"
                "**Test du T1** : si tu le lis seul dans le feed et que tu n'as PAS envie de "
                "cliquer pour la suite, ce n'est pas un hook. Recommence.\n\n"
                "#### Signal de continuation en fin de T1 (obligatoire)\n\n"
                "Le T1 doit faire comprendre au lecteur **qu'il y a une suite à lire**. Sans "
                "ce signal, le T1 est lu comme un tweet isolé et les T2-T_N perdent leurs vues. "
                "La forme du signal **s'adapte à la persona** — pas de marqueur unique :\n"
                "- `...` ou `…` en fin (registre intime, suspens, persona introspective)\n"
                "- `↓` ou `⬇️` (registre direct, persona qui guide) — **pas de point final "
                "avant la flèche** : la phrase précédente s'enchaîne sans ponctuation pour "
                "garder la fluidité visuelle (ex. `... la suite ↓` et non `... la suite. ↓`)\n"
                "- `:` en fin (registre annonciateur, persona qui pose une thèse/un constat "
                "puis l'illustre ou l'argumente dans les tweets suivants)\n"
                "- Numérotation `1/N` où N = nombre total de tweets du thread (registre "
                "structuré, persona qui annonce une démonstration)\n"
                "- Tout autre marqueur naturel à la voix (emoji signature, connecteur visuel) "
                "du moment qu'il signale visiblement la suite\n\n"
                "**L'intention prime sur la forme** : choisir le signal qui incarne le mieux "
                "la persona et le ton du thread en cours. Ne PAS plaquer le même marqueur sur "
                "tous les threads. Un T1 sans aucun signal de continuation est cassé.\n\n"
                "#### Rôle narratif par position\n\n"
                "Chaque tweet du thread occupe un rôle. La cohérence vient du **chaînage "
                "explicite** : chaque tweet REPREND un mot, une image, une question du précédent. "
                "Pas de saut sec, pas de tweet qui pourrait être lu indépendamment.\n\n"
                "- **T1** : hook (voir ci-dessus).\n"
                "- **T2** : escalade ou contexte qui creuse — répond à la tension du T1 en "
                "ouvrant un nouveau pan, pas en résolvant. Reprise EXPLICITE d'un mot/idée du T1 "
                "(le lecteur doit sentir le fil).\n"
                "- **T_milieu** (T3 à T_avant-dernier) : péripéties, détails concrets, dialogue, "
                "micro-scène. Chaque tweet ajoute UNE chose nouvelle, pas une variation du "
                "précédent.\n"
                "- **T_dernier** : chute, leçon, pivot Compaatible si applicable. Idéalement "
                "référence finale au T1 (boucle narrative) ou ouverture vers une vérité plus large.\n\n"
                "**Anti-exemple** : 5 tweets qui disent chacun \"la même observation sous un angle "
                "différent\" = pas un thread, c'est 5 tweets isolés mal collés. Si tu peux lire les "
                "tweets dans n'importe quel ordre, ce n'est pas un thread.\n\n"
                "#### Cohérence narrative\n\n"
                "Avant d'écrire le T1, **formule mentalement l'arc en 1 phrase** (le point de "
                "départ et le point d'arrivée du fil narratif). Tous les tweets du thread "
                "doivent servir cet arc. Si un tweet ne le sert pas, il n'est pas dans le thread "
                "(et probablement pas dans le corpus tout court).\n\n"
                "Les éléments concrets (personnages secondaires, lieux, objets) introduits dans "
                "un tweet DOIVENT être suivis ou refermés. Si tu nommes quelqu'un en T2, soit la "
                "personne réapparaît, soit on comprend pourquoi elle disparaît. Pas de personnage "
                "flottant.\n\n"
                "**Invariants techniques** : chaque tweet ≤ 280 caractères, T1 lisible seul (il "
                "sera affiché à l'unité dans le feed), `thread_key` en kebab-case partagé par "
                "tous les tweets du thread.\n\n"
                "### Énumérations numérotées : un item = un tweet (règle dure)\n\n"
                "Si tu écris une énumération `1. … 2. … 3. …` (ou `1) … 2) … 3) …`) avec **2 items "
                "ou plus**, chaque item DOIT vivre dans son propre tweet du thread. Jamais "
                "d'items entassés dans un seul post.\n\n"
                "**Forme attendue** :\n"
                "- T1 (hook) : pose la promesse ou le constat qui annonce la liste.\n"
                "- T2 : `1. <item 1> + son détail` (la phrase qui développe le point).\n"
                "- T3 : `2. <item 2> + son détail`.\n"
                "- T4 : `3. <item 3> + son détail`.\n"
                "- T_last : chute, pivot, ou ouverture.\n\n"
