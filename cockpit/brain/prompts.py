                "Vérifie chaque caractère du slug avant de l'insérer.\n"
                "(b) **Le lien doit être amené par la voix de la persona**, pas posé en fin de tweet "
                "sans rien dire. Ton « copine qui passe un article », jamais « voici un lien ».\n"
