        "### 6. LUMIÈRE — celle du moment, pas celle d'un shooting\n"
        "- Lumière naturelle uniquement (jamais flash photo, jamais lumière studio).\n"
        "- Source précise : fenêtre latérale fin de matinée, lampe d'appoint chaude le soir "
