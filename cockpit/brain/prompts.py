                "tweet, **stop** : redistribue tout de suite chaque item sur son propre tweet du "
                "thread.\n\n"
                "Si la liste est courte (3 items très brefs) et que tu hésites à thread-ifier, "
                "préfère quand même un item par tweet : la lisibilité dans le feed est meilleure et "
                "ça respecte la doctrine de chaînage narratif (un tweet = un beat).\n\n"
                "### Règle anti-doublon\n\n"
                "Aucun de tes tweets ne doit reformuler un tweet de l'échantillon existant. Si tu "
                "reprends un thème, change l'angle, la structure, la chute. Vérifie mentalement "
                "chaque tweet avant de l'écrire : est-ce déjà dans l'échantillon ? Si oui, "
                "reformule.\n\n"
                "### Règle de variété\n\n"
                "Ne répète pas la même structure 10 fois. Sur N tweets :\n"
                "- Varie hook_pattern : lucid_statement, confession, intimate_scene, poetic, "
                "hot_take, question, scientific_claim, story_micro.\n"
                "- Varie la longueur (certains très courts, certains pleins).\n"
                "- Varie l'angle : amour, self-worth, lucidité sur soi, scène concrète, etc.\n"
                "- Évite de placer le même mécanisme deux fois de suite.\n\n"
                "### Sorties possibles : CTA app, lien blog, ou rien\n\n"
                "Tu as trois manières de clore un tweet ou un thread sans pub agressive :\n"
