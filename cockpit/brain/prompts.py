        "incarné. **Ils doivent appartenir à CETTE persona précise, déduits de sa backstory.**\n\n"
        "### 8. STYLE PHOTOGRAPHIQUE — vraie photo amateur\n"
        "- **Type d'appareil implicite** : iPhone récent en mode normal (pas Portrait, le "
