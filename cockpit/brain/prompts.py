                "#### Résolution avec le filtre \"Pas intéressé\"\n\n"
                "Le filtre plus haut interdit le \"rage-bait ou ton aigri sur un sujet "
                "sensible\". **Un quote-trigger clivant n'est pas du rage-bait** parce que :\n"
